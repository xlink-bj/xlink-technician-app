import { readFileSync } from 'node:fs'
import { describe, expect, it } from 'vitest'

const source = (path: string) => readFileSync(new URL(`../../${path}`, import.meta.url), 'utf8')

const craft = source('src/shared/ui/mobile-craft-v1.scss')
const q01 = source('src/features/work-orders/quotation/Q01EntryScreen.vue')
const q01Shell = source('src/shared/ui/ActionWorkspaceShell.vue')
const q01Footer = source('src/features/work-orders/quotation/QuotationActionWorkspace.vue')
const c01 = source('src/pages/work-orders/signing-order-read.vue')
const heading = source('src/shared/ui/AppCraftHeading.vue')
const globals = source('src/shared/ui/design-system.scss')

describe('DS-05: Q01 V2 Mobile Craft reused by C01', () => {
  it('uses a single opt-in visual standard, not another global skin', () => {
    expect(craft).toContain('.xl-craft {')
    expect(globals).toContain("mobile-craft-v1.scss")
    expect(globals).toContain('--app-craft-action: #1769dc')
    expect(craft).toContain('--xl-blue: var(--app-craft-action)')
    expect(globals).toContain('--app-craft-field-surface: #f1f5fa')
    expect(craft).toContain('--xl-field-bg: var(--app-craft-field-surface)')
    expect(globals).toContain('--app-craft-placeholder: #607188')
    expect(craft).toContain('--xl-placeholder: var(--app-craft-placeholder)')
    expect(craft).toContain('.xl-craft__control:focus')
    expect(craft).toContain('.xl-craft__control:disabled')
    expect(craft).toContain('.xl-craft__control[aria-invalid="true"]')
    expect(craft).toContain('.xl-craft__action-primary:disabled')
  })
  it('both business pages reuse shared craft heading and surfaces', () => {
    expect(heading).toContain('defineProps')
    expect(q01).toContain('AppCraftHeading')
    expect(c01).toContain('AppCraftHeading')
    expect(q01).toContain('xl-craft__progress-track')
    expect(q01).toContain('xl-craft__control--selector')
    expect(q01).toContain('xl-craft__control--textarea')
    expect(q01).toContain('xl-craft__control--input')
    expect(c01).toContain('xl-craft__surface')
    expect(c01).toContain('xl-craft__value')
    expect(c01).toContain('signing-read-hero-money')
    expect(c01).toContain('signing-read-stage')
    expect(q01Shell).toContain("'xl-craft': compactQuoteEntry")
    expect(q01Footer).toContain('xl-craft__action-primary')
    expect(q01Footer).toContain('xl-craft__action-secondary')
  })
  it('does not grant signing, business submission or quotation authority to craft primitives', () => {
    expect(q01).toContain("@input=\"emit('quantity-input', $event)\"")
    expect(q01).toContain("emit('repair-parts-change'")
      // Parent remains the only owner of all quotation actions
    expect(q01Footer).toContain('@tap="advanceFirstRepairStep"')
    expect(q01Footer).toContain('@tap="composition.flushDraft"')
    expect(c01).toContain('signing-order-read-no-write')
    expect(c01).toContain('signing-order-read-sign-disabled')
    expect(c01).toContain('signing-contract-prod-blocked')
    expect(heading).not.toMatch(/fetch\(|axios|useSigning|useQuotation|submitOrder/)
    expect(craft).not.toMatch(/fetch\(|axios|api\//)
  })
})
