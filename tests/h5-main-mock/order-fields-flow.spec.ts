import { expect, test, type Page } from '@playwright/test'
test('430×932: dynamic quotation fields persist through quote and Order readback', async ({ page }) => {
  test.setTimeout(120_000)
  page.setDefaultTimeout(15_000)
  await page.setViewportSize({ width: 430, height: 932 })
  const external: string[] = []
  await page.context().route('**/*', async route => {
    if (new URL(route.request().url()).origin === 'http://localhost:5174') return route.continue()
    external.push(route.request().url()); await route.abort()
  })
  async function open019Quotation(page: Page) {
    await page.goto('/#/pages/index/index?devReview=1', { waitUntil: 'domcontentloaded' })
    await page.getByTestId('mock-continuous-journey-entry').click()
    await page.locator('.action-content-field--note textarea').fill('阶段 A 移动端：平屋顶预约')
    await page.getByTestId('mock-journey-advance').click()
    await expect(page).toHaveURL(/work-orders\/detail/)
    await page.locator('.primary-task-action').click()
    const repairPart = page.getByTestId('survey-part-picker-trigger')
    await expect(repairPart).toBeVisible()
    await repairPart.click()
    await expect(page.getByTestId('survey-part-picker-panel')).toBeVisible()
    await page.getByTestId('survey-repair-part-parents').locator('.app-cascade-selector__parent').first().click()
    await page.getByTestId('survey-repair-part-children').locator('.app-cascade-selector__child').first().click()
    await page.getByTestId('survey-part-picker-confirm').click()
    await expect(page.getByTestId('dynamic-field-squareMeter')).toBeVisible()
    await page.getByTestId('dynamic-field-squareMeter').locator('input').fill('12')
    await page.getByTestId('mock-journey-advance').click()
    await page.locator('.primary-task-action').click()
    await expect(page.getByTestId('quotation-order-hub')).toBeVisible()
    await page.getByTestId('quotation-hub-create-unverified').click()
    await expect(page.getByTestId('quotation-state-ready')).toBeVisible()
    await expect(page.getByTestId('a-stage-mock-order-panel')).toBeVisible()
  }

  await open019Quotation(page)
      await page.getByTestId('quotation-add-group').click()
      await page.getByTestId('quotation-first-step-repair-parts-trigger').click()
      const picker = page.getByTestId('quotation-repair-part-picker')
      await picker.locator('.app-cascade-selector__parent').filter({ hasText: '屋面' }).click()
      await page.getByTestId('quotation-repair-part-picker-done').click()
      await page.getByTestId('quotation-first-step-description').locator('textarea').fill('平屋顶局部修缮')
      await page.getByTestId('quotation-first-step-quantity').locator('input').fill('12')
      await page.getByTestId('quotation-first-step-select-products').click()
      await expect(page.getByTestId('order-fields-selection-blocked')).toBeVisible()
      await page.getByTestId('order-field-mock-order-mode').getByText('否', { exact: true }).click()
      await expect(page.getByTestId('order-extfield-editor')).toHaveAttribute('data-draft-status', 'saved_local')
      await page.getByTestId('quotation-first-step-select-products').click()
      await page.getByTestId('quotation-catalog-kind-material').click()
      const materialId = 'mock-catalog-material-ordinary-1'
      await page.getByTestId(`quotation-catalog-add-material-${materialId}`).click()
      if (await page.getByTestId('quotation-catalog-close').isVisible()) await page.getByTestId('quotation-catalog-close').click()
      await page.getByTestId('quotation-browse-quotation-group-1').click()
      await page.getByTestId('quotation-catalog-kind-procedure').click()
      await page.getByTestId('quotation-catalog-add-procedure-mock-catalog-procedure-seal').click()

  if (await page.getByTestId('quotation-catalog-close').isVisible()) await page.getByTestId('quotation-catalog-close').click()
  const editor = page.getByTestId('order-extfield-editor')
  await expect(editor).toBeVisible()
  await page.getByTestId('order-field-mock-order-mode').getByText('是', { exact: true }).click()
  await expect(page.getByTestId('order-field-mock-order-note')).toContainText('请填写此项')
  await page.screenshot({ path: 'test-results/main-h5-mock/evidence/order-fields-required-error-430x932.png', fullPage: true })
  await page.getByTestId('order-field-mock-order-note').locator('textarea').fill('现场范围已核对')
  await page.getByTestId('order-field-mock-order-number').locator('input').fill('invalid')
  await expect(page.getByTestId('order-field-mock-order-number')).toContainText('请检查')
  await page.getByTestId('order-field-mock-order-number').locator('input').fill('0')
  await page.getByTestId('order-cascade-mock-order-area-trigger').click()
  await page.getByTestId('order-cascade-mock-order-area-panel').getByText('北京市 / 北京市城区 / 东城区', { exact: true }).click()
  await page.getByTestId('order-cascade-mock-order-area-panel').getByLabel('关闭选择').click()
  await expect(page.getByTestId('order-cascade-mock-order-area-trigger')).toContainText('请选择')
  await expect(page.getByTestId('order-field-mock-order-note').locator('textarea')).toHaveValue('现场范围已核对')
  await page.getByTestId('order-cascade-mock-order-area-trigger').click()
  await page.getByTestId('order-cascade-mock-order-area-panel').getByText('北京市 / 北京市城区 / 东城区', { exact: true }).click()
  await page.screenshot({ path: 'test-results/main-h5-mock/evidence/order-fields-area-selection-430x932.png' })
  await page.getByTestId('order-cascade-mock-order-area-confirm').click()
  await page.getByTestId('order-cascade-mock-order-path-trigger').click()
  await page.getByTestId('order-cascade-mock-order-path-panel').getByText('示例区域', { exact: true }).click()
  await page.getByTestId('order-cascade-mock-order-path-panel').locator('.app-cascade-selector__child').filter({ hasText: '施工现场' }).click()
  await page.getByTestId('order-cascade-mock-order-path-confirm').click()
  await expect(page.getByTestId('order-extfield-editor')).toHaveAttribute('data-draft-status', 'saved_local')
  await expect(page.getByTestId('a-stage-order-create')).toBeEnabled()
  await page.screenshot({ path: 'test-results/main-h5-mock/evidence/order-fields-filled-430x932.png', fullPage: true })
  const other = await page.context().newPage()
  await other.goto(page.url(), { waitUntil: 'domcontentloaded' })
  await expect(other.getByTestId('quotation-order-hub')).toBeVisible()
  await other.getByTestId('quotation-hub-create-unverified').click()
  await expect(other.getByTestId('order-extfield-editor')).toBeVisible()
  const revision = Number(await editor.getAttribute('data-revision'))
  await page.getByTestId('order-field-mock-order-number').locator('input').fill('1')
  await expect.poll(async () => Number(await editor.getAttribute('data-revision'))).toBeGreaterThan(revision)
  await expect(page.getByTestId('order-extfield-editor')).toHaveAttribute('data-draft-status', 'saved_local')
  await page.getByTestId('order-field-mock-order-number').locator('input').fill('0')
  await expect(page.getByTestId('order-extfield-editor')).toHaveAttribute('data-draft-status', 'saved_local')
  await expect.poll(async () => Number(await editor.getAttribute('data-revision'))).toBeGreaterThan(revision + 1)
  await expect(page.getByTestId('order-field-mock-order-number').locator('input')).toHaveValue('0')
  await other.getByTestId('order-field-mock-order-note').locator('textarea').fill('过时页面输入')
  await expect(other.getByTestId('order-extfield-editor')).toHaveAttribute('data-draft-status', 'save_failed')
  await expect(other.locator('.action-workspace-draft-status')).toContainText('报价资料保存失败或已在其他页面修改')
  await expect(other.getByTestId('order-field-mock-order-note').locator('textarea')).toHaveValue('过时页面输入')
  await other.close()
  await page.getByTestId('a-stage-order-create').click()
  await page.getByTestId('a-stage-order-confirm').click()
  await expect(page.getByTestId('a-stage-quote-readback')).toBeVisible()
  await page.reload({ waitUntil: 'domcontentloaded' })
  await expect(editor.or(page.getByTestId('quotation-order-hub'))).toBeVisible()
  if (await page.getByTestId('quotation-order-hub').isVisible()) await page.getByTestId('quotation-hub-create-unverified').click()
  await expect(editor).toBeVisible()
  await expect(page.getByTestId('order-field-mock-order-note').locator('textarea')).toHaveValue('现场范围已核对')
  await expect(page.getByTestId('order-field-mock-order-number').locator('input')).toHaveValue('0')
  await expect(page.getByTestId('order-cascade-mock-order-area-trigger')).toContainText('东城区')
  await expect(page.getByTestId('a-stage-order-convert')).toBeEnabled()
  await page.getByTestId('a-stage-order-convert').click()
  await page.getByTestId('a-stage-order-convert-confirm').click()
  await expect(page.getByTestId('a-stage-order-readback')).toBeVisible()
  await page.screenshot({ path: 'test-results/main-h5-mock/evidence/order-fields-order-readback-430x932.png', fullPage: true })
  expect(external).toEqual([])
})
