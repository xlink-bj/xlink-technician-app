import type { MediaTaskLookupScope } from '@shared/ports'
import { asOpaqueId, type MediaTaskScope, type MediaUploadTask, type MediaUploadTaskId, type UploadedMediaRef } from '@shared/types'

const generatedTaskPrefix = 'media-upload-task:'

/** The existing local queue identity format; it is not a remote media ID. */
export function taskIdFor(scope: Omit<MediaTaskScope, 'localAssetId'>, localAssetId: string): MediaUploadTaskId {
  const parts = [
    'media-upload-task', String(scope.userId), String(scope.workOrderId), String(scope.workflowNodeId),
    String(scope.formDefinitionId ?? ''), String(scope.formDataId ?? ''), scope.fieldId, scope.valueKey, localAssetId,
  ]
  return asOpaqueId<'MediaUploadTaskId'>(parts.map(part => encodeURIComponent(part)).join(':'))
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return value !== null && typeof value === 'object' && !Array.isArray(value)
}

function isText(value: unknown): value is string {
  return typeof value === 'string' && value.trim().length > 0
}

function optionalText(record: Record<string, unknown>, keys: readonly string[]): boolean {
  return keys.every(key => record[key] === undefined || isText(record[key]))
}

/** Validates the neutral receipt shape, not provider ownership or remote existence. */
export function isUploadedMediaRef(value: unknown): value is UploadedMediaRef {
  return isRecord(value)
    && isText(value.url)
    && ['camera', 'library', 'file'].includes(value.source as string)
    && value.uploadState === 'uploaded'
    && optionalText(value, ['key', 'fileName', 'extension', 'mimeType'])
}

export function isMediaTaskLookupScope(value: unknown): value is MediaTaskLookupScope {
  return isRecord(value)
    && ['userId', 'workOrderId', 'workflowNodeId'].every(key => isText(value[key]))
    && optionalText(value, ['formDefinitionId', 'formDataId', 'fieldId', 'valueKey'])
}

function isTaskScope(value: unknown): value is MediaTaskScope {
  return isRecord(value)
    && ['fieldId', 'valueKey', 'localAssetId'].every(key => isText(value[key]))
    && isMediaTaskLookupScope(value)
}

function isEvidence(value: unknown): boolean {
  if (value === undefined) return true
  if (!isRecord(value) || !optionalText(value, ['capturedAt'])) return false
  if (value.postUploadPolicy !== undefined
    && value.postUploadPolicy !== 'none'
    && value.postUploadPolicy !== 'remote_location_watermark') return false
  if (value.location === undefined) return true
  const location = value.location
  return isRecord(location)
    && typeof location.latitude === 'number' && Number.isFinite(location.latitude)
    && typeof location.longitude === 'number' && Number.isFinite(location.longitude)
    && (location.coordinateSystem === 'gcj02' || location.coordinateSystem === 'wgs84')
    && isText(location.capturedAt)
    && (location.accuracy === undefined
      || (typeof location.accuracy === 'number' && Number.isFinite(location.accuracy)))
    && optionalText(location, ['address'])
}

function isLastError(value: unknown): boolean {
  return value === undefined || (isRecord(value)
    && ['session_invalid', 'authorization_denied', 'validation', 'unsupported_capability',
      'network_retryable', 'server_terminal', 'cancelled'].includes(value.category as string)
    && isText(value.message)
    && typeof value.retryable === 'boolean'
    && value.retryable === (value.category === 'network_retryable')
    && optionalText(value, ['code', 'reason']))
}

export function isMediaUploadTask(value: unknown, taskId?: MediaUploadTaskId): value is MediaUploadTask {
  if (!isRecord(value) || value.schemaVersion !== 1
    || !isText(value.taskId) || (taskId !== undefined && value.taskId !== taskId)
    || !['queued', 'preprocessing', 'ready_to_upload', 'uploading', 'source_uploaded',
      'postprocessing', 'uploaded', 'failed_retryable', 'failed_terminal'].includes(value.state as string)
    || !Number.isSafeInteger(value.attempts) || (value.attempts as number) < 0
    || !isText(value.createdAt) || !isText(value.updatedAt)
    || !isTaskScope(value.scope)
    || !isEvidence(value.evidence) || !isLastError(value.lastError)) return false

  if (value.state === 'failed_retryable' || value.state === 'failed_terminal') {
    if (!isRecord(value.lastError)
      || value.lastError.retryable !== (value.state === 'failed_retryable')) return false
  } else if (value.lastError !== undefined) {
    // Enqueue and every retry/completion transition clear failure metadata.
    // A contradictory active state must not erase evidence of an unknown ACK.
    return false
  }

  // Bind IDs generated by this queue to their original semantic scope. Older
  // opaque IDs remain supported, with read-key binding and shape validation.
  // Neither check authenticates ownership or proves a remote object exists.
  if (value.taskId.startsWith(generatedTaskPrefix)) {
    try {
      if (value.taskId !== taskIdFor(value.scope, value.scope.localAssetId)) return false
    } catch {
      return false
    }
  }

  if (value.sourceUploadedRef !== undefined && !isUploadedMediaRef(value.sourceUploadedRef)) return false
  // Only the location-watermark path creates source checkpoints, after its
  // location guard. Resuming a checkpoint must retain that original context.
  if (value.sourceUploadedRef !== undefined && (!isRecord(value.evidence)
    || value.evidence.postUploadPolicy !== 'remote_location_watermark'
    || !isRecord(value.evidence.location))) return false
  if (value.uploadedRef !== undefined && !isUploadedMediaRef(value.uploadedRef)) return false
  // A final receipt belongs only to the completed state. Source checkpoints
  // cannot be treated as queued work and dispatched again.
  if (value.state === 'uploaded' ? !isUploadedMediaRef(value.uploadedRef) : value.uploadedRef !== undefined) return false
  if (value.state === 'source_uploaded' || value.state === 'postprocessing') {
    if (!isUploadedMediaRef(value.sourceUploadedRef)) return false
  }
  if (['queued', 'preprocessing', 'ready_to_upload', 'uploading'].includes(value.state as string)
    && value.sourceUploadedRef !== undefined) return false
  if (value.state === 'uploaded' && isRecord(value.evidence)
    && value.evidence.postUploadPolicy === 'remote_location_watermark'
    && !isUploadedMediaRef(value.sourceUploadedRef)) return false
  return true
}
